/**
 * Renders an 8x8 pixel string at (x, y) on the canvas using the active palette.
 */
export function drawText8x8(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  paletteMode: PaletteMode,
  inkShade: 0 | 1 | 2 | 3 = 3
): void {
  const palette = PALETTES[paletteMode];
  ctx.fillStyle = palette[inkShade];
  const upper = text.toUpperCase();

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const glyph = GLYPHS[ch] ?? GLYPHS[' '];
    const baseX = x + i * 8;
    for (let r = 0; r < 8; r++) {
      const rowStr = glyph[r];
      for (let c = 0; c < 8; c++) {
        if (rowStr[c] !== '.') {
          ctx.fillRect(baseX + c, y + r, 1, 1);
        }
      }
    }
  }
}
